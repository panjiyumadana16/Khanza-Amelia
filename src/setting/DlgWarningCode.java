    public void tampil() {
        String sql="select * from warning_code LIMIT 1";
        prosesCari(sql);
    }

    private void prosesCari(String sql) {
        try{
            java.sql.Statement stat=koneksi.createStatement();
            ResultSet rs=stat.executeQuery(sql);
            if(rs.next()){
                TKetWarning.setText(rs.getString("keterangan"));
                TWaktuWarning.setText(rs.getString("waktu_notif"));
                BtnCodeRed.setEnabled(false);BtnCodeBlue.setEnabled(false);
                BtnCodePink.setEnabled(false);BtnCodeBlack.setEnabled(false);
                BtnCodeMaternal.setEnabled(false);BtnCodeGreen.setEnabled(false);
                BtnStopWarning.setEnabled(true);
                TKetWarning.setEnabled(false);
            } else {
                emptTeks();
                BtnCodeRed.setEnabled(true);BtnCodeBlue.setEnabled(true);
                BtnCodePink.setEnabled(false);BtnCodeBlack.setEnabled(false);
                BtnCodeGreen.setEnabled(false);
                if(WARNINGCODEMATERNAL.equals("yes")){
                    BtnCodeMaternal.setEnabled(true);
                } else {
                    BtnCodeMaternal.setEnabled(false);
                }
                BtnStopWarning.setEnabled(false);
            }
        }catch(SQLException e){
            System.out.println("Notifikasi : "+e);
        }
    }

    public void emptTeks() {
        TKetWarning.setText("");
        TWaktuWarning.setText("");
        TKetWarning.setEnabled(true);
        TKetWarning.requestFocus();
    }
    
